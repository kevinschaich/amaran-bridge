#!/usr/bin/env python3
"""Generate main/mesh_config.h from the amaran Desktop app's database.

The app stores the mesh keys and every fixture's unicast address in a SQLite
file; this reads it directly so a clone of this folder is self-contained.

    python3 tools/gen_mesh_config.py                 # autodetect the database
    python3 tools/gen_mesh_config.py --db path.db --iv 0x2a

The output is key-bearing and gitignored. Re-run it whenever fixtures are
added, removed or renamed in the app -- a stale address means commands go to
nobody, silently.
"""
import argparse, glob, json, os, re, sqlite3, sys

DEFAULT_DB = os.path.expanduser(
    "~/Library/Application Support/amaran Desktop/*/amaran.db")

# The database records addresses and MACs but not what a fixture can do, so
# capabilities come from a hand-maintained file. Anything absent falls back to
# DEFAULT_CAPS, which is deliberately permissive: an over-generous colour wheel
# is a cosmetic annoyance, a missing one looks like broken firmware.
DEFAULT_CAPS = {"has_color": True, "has_gm": True,
                "cct_min": 2700, "cct_max": 6500}


def key_for(name):
    k = re.sub(r"[^a-z0-9]+", "_", name.strip().lower()).strip("_")
    return (k or "fixture")[:19]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db")
    ap.add_argument("--out", default="main/mesh_config.h")
    ap.add_argument("--caps", default="tools/capabilities.json")
    ap.add_argument("--iv", default="0x00000000",
                    help="initial IV index; must be within 42 of the network's "
                         "real value or the node never syncs (see README)")
    args = ap.parse_args()

    db = args.db or next(iter(sorted(glob.glob(DEFAULT_DB), reverse=True)), None)
    if not db or not os.path.exists(db):
        sys.exit("amaran database not found; pass --db")

    caps = {}
    if os.path.exists(args.caps):
        caps = json.load(open(args.caps))

    con = sqlite3.connect(db)
    net_key, app_key = con.execute(
        "select net_key, app_key from mesh limit 1").fetchone()
    rows = con.execute("select node_address, name, mac_address from fixtures "
                       "order by node_address").fetchall()
    if not rows:
        sys.exit("no fixtures in %s" % db)

    def carr(hexstr):
        b = bytes.fromhex(hexstr)
        return ", ".join("0x%02x" % x for x in b)

    out = ["/* Generated by tools/gen_mesh_config.py -- DO NOT EDIT BY HAND.",
           " * Source: %s" % db,
           " *",
           " * KEY-BEARING. Never commit, paste or share this file.",
           " */",
           "",
           "#ifndef AMARAN_MESH_CONFIG_H",
           "#define AMARAN_MESH_CONFIG_H",
           "",
           "#include <stdint.h>",
           "#include <stdbool.h>",
           "",
           "#define AMARAN_DEFAULT_LIGHT_COUNT %d" % len(rows),
           "",
           "typedef struct {",
           "    /* Fixed arrays, not pointers: the table is read at runtime and",
           "       must not point into flash-mapped constants. */",
           "    char key[20];",
           "    char name[32];",
           "    uint8_t mac[6];        /* big-endian, as printed */",
           "    uint16_t address;      /* mesh unicast address */",
           "    bool has_color;        /* expose an HS colour wheel */",
           "    bool has_gm;           /* accepts green/magenta tint */",
           "    uint16_t cct_min;",
           "    uint16_t cct_max;",
           "} amaran_light_t;",
           "",
           "static const uint8_t AMARAN_NET_KEY[16] = { %s };" % carr(net_key),
           "static const uint8_t AMARAN_APP_KEY[16] = { %s };" % carr(app_key),
           "static const uint32_t AMARAN_IV_INDEX_INITIAL = %s;" % args.iv,
           "",
           "#define AMARAN_GROUP_ALL 0xC000",
           "#define AMARAN_BROADCAST 0xFFFF",
           "",
           "static const amaran_light_t "
           "AMARAN_DEFAULT_LIGHTS[AMARAN_DEFAULT_LIGHT_COUNT] = {"]

    for addr, name, mac in rows:
        k = key_for(name)
        c = dict(DEFAULT_CAPS, **caps.get(k, {}))
        mb = ", ".join("0x%02x" % int(x, 16) for x in mac.split(":"))
        out.append('    { .key = "%s", .name = "%s", .mac = { %s }, '
                   '.address = 0x%04x, .has_color = %s, .has_gm = %s, '
                   '.cct_min = %d, .cct_max = %d },'
                   % (k, name[:31], mb, addr,
                      "true" if c["has_color"] else "false",
                      "true" if c["has_gm"] else "false",
                      c["cct_min"], c["cct_max"]))

    out += ["};", "", "#endif /* AMARAN_MESH_CONFIG_H */", ""]
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    open(args.out, "w").write("\n".join(out))
    print("wrote %s (%d fixtures)" % (args.out, len(rows)))


if __name__ == "__main__":
    main()
